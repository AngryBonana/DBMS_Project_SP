/**
 * @file query_classifier.h
 * @brief Эвристическая классификация SQL-запросов по ожидаемой длительности.
 *
 * На этапе 2 используется простой анализ текста запроса (без парсера AST):
 * операции DDL/DML считаются потенциально длительными и уходят в асинхронную
 * очередь, тогда как SELECT обрабатывается синхронно. На этапе 4 классификатор
 * можно заменить или дополнить реальными метриками времени выполнения.
 */
#pragma once

#include <string>

namespace executor {

/// Режим выполнения запроса, выбираемый перед постановкой в очередь.
enum class ExecutionMode {
    Sync,   ///< Немедленное выполнение в потоке вызывающего кода
    Async   ///< Постановка в очередь, немедленный возврат GUID
};

/// Определяет, следует ли выполнять запрос асинхронно (длительная операция).
ExecutionMode classifyExecutionMode(const std::string& query);

}  // namespace executor
